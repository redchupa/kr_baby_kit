const DICT = {
  en: EN,
  ko: KO,
  ja: JA,
  "zh-Hans": ZH,
  es: ES,
  fr: FR,
  de: DE,
  pt: PT,
};

export function getStrings(lang) {
  return DICT[lang] || EN;
}

export function fmtMinutesI18n(min, lang) {
  const total = Math.round(Number(min || 0));
  const h = Math.floor(total / 60);
  const m = total % 60;
  if (lang === "ko") return h > 0 ? `${h}시간 ${m}분` : `${m}분`;
  if (lang === "ja") return h > 0 ? `${h}時間${m}分` : `${m}分`;
  if (lang === "zh-Hans") return h > 0 ? `${h}小时${m}分` : `${m}分钟`;
  return h > 0 ? `${h}h ${m}m` : `${m}m`;
}

export function fmtAgoI18n(iso, lang) {
  if (!iso) return "";
  const ts = Date.parse(iso);
  if (Number.isNaN(ts)) return "";
  const mins = Math.max(0, Math.floor((Date.now() - ts) / 60000));
  if (mins < 1) {
    return (
      { ko: "방금 전", ja: "たった今", "zh-Hans": "刚刚", es: "Ahora", fr: "À l'instant", de: "Gerade eben", pt: "Agora" }[
        lang
      ] || "Just now"
    );
  }
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  if (h >= 24) {
    const d = Math.floor(h / 24);
    if (lang === "ko") return `${d}일 전`;
    if (lang === "ja") return `${d}日前`;
    if (lang === "zh-Hans") return `${d}天前`;
    if (lang === "es") return `hace ${d}d`;
    if (lang === "fr") return `il y a ${d}j`;
    if (lang === "de") return `vor ${d}T`;
    if (lang === "pt") return `há ${d}d`;
    return `${d}d ago`;
  }
  if (lang === "ko") return h > 0 ? `${h}시간 ${m}분 전` : `${m}분 전`;
  if (lang === "ja") return h > 0 ? `${h}時間${m}分前` : `${m}分前`;
  if (lang === "zh-Hans") return h > 0 ? `${h}小时${m}分前` : `${m}分钟前`;
  if (lang === "es") return h > 0 ? `hace ${h}h ${m}m` : `hace ${m}m`;
  if (lang === "fr") return h > 0 ? `il y a ${h}h ${m}m` : `il y a ${m}m`;
  if (lang === "de") return h > 0 ? `vor ${h}h ${m}m` : `vor ${m}m`;
  if (lang === "pt") return h > 0 ? `há ${h}h ${m}m` : `há ${m}m`;
  return h > 0 ? `${h}h ${m}m ago` : `${m}m ago`;
}
