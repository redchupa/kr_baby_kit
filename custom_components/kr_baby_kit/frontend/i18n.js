/* 8-language internationalization (i18n) module for Baby Kit sidebar panel.
 * Supported: ko, en, ja, zh-Hans, es, fr, de, pt
 */

export const LANGUAGES = [
  { code: "ko", short: "KO", label: "한국어" },
  { code: "en", short: "EN", label: "English" },
  { code: "ja", short: "JA", label: "日本語" },
  { code: "zh-Hans", short: "中文", label: "简体中文" },
  { code: "es", short: "ES", label: "Español" },
  { code: "fr", short: "FR", label: "Français" },
  { code: "de", short: "DE", label: "Deutsch" },
  { code: "pt", short: "PT", label: "Português" },
];

export const VALID_LANG_PREFS = ["auto", ...LANGUAGES.map((l) => l.code)];

export function resolveLang(prefLang, hassLang) {
  if (prefLang && prefLang !== "auto" && LANGUAGES.some((l) => l.code === prefLang)) {
    return prefLang;
  }
  const raw = String(hassLang || "en").toLowerCase();
  if (raw.startsWith("ko")) return "ko";
  if (raw.startsWith("ja")) return "ja";
  if (raw.startsWith("zh")) return "zh-Hans";
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("fr")) return "fr";
  if (raw.startsWith("de")) return "de";
  if (raw.startsWith("pt")) return "pt";
  return "en";
}

export function getLangMeta(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[1];
}

